//! What classifies a collection for discovery (#1356): its WIS2 topic as an
//! OGC `themes` concept, and the WMO Core Metadata Profile (WCMP2) records in
//! a WIS2 Global Discovery Catalogue that describe it.
//!
//! A topic is a path of the WIS2 Topic Hierarchy below its
//! earth-system-discipline level (`weather/prediction/forecast/…`), at any
//! depth, validated against the vendored release
//! (`assets/wis2-topic-hierarchy-1.3.0`). The levels above it (channel,
//! version, system, centre, notification type, data policy) say who
//! publishes it and how, not what it is, and are never part of a topic.
//! A collection takes its topic from `[discovery] wis2_topic`, or else from
//! the topics its WIS2 subscriptions name ([`Wis2Topic::from_subscription`]).
//!
//! The API layer serializes [`themes`] and links each of
//! [`Discovery::records`] at [`Catalogue::record_url`].

use std::collections::HashMap;
use std::sync::LazyLock;

use serde::{Deserialize, Serialize};

use crate::config::CollectionConfig;

/// The vocabulary of a collection's topic concepts: the WIS2 Topic
/// Hierarchy from its earth-system-discipline level down.
pub const TOPIC_SCHEME: &str = "https://codes.wmo.int/wis/topic-hierarchy/earth-system-discipline";

/// The Global Discovery Catalogue records resolve in without a configured
/// `[discovery] catalogue`.
pub const DEFAULT_CATALOGUE: &str = "https://wis2-gdc.weather.gc.ca";

/// Every valid earth-system-discipline path, its status and description,
/// generated by `scripts/vendor-wis2-topic-hierarchy.py`.
const HIERARCHY_TABLE: &str =
    include_str!("../assets/wis2-topic-hierarchy-1.3.0/earth-system-discipline.tsv");

/// The level below which WIS2 lets a publisher add levels of its own.
const EXPERIMENTAL: &str = "experimental";

/// The vendored hierarchy, parsed once.
struct Hierarchy {
    /// Every valid path and its description.
    descriptions: HashMap<&'static str, &'static str>,
    /// The names each path's children may take, in name order; `""` keys
    /// the disciplines.
    children: HashMap<&'static str, Vec<&'static str>>,
}

static HIERARCHY: LazyLock<Hierarchy> = LazyLock::new(|| {
    let mut hierarchy = Hierarchy {
        descriptions: HashMap::new(),
        children: HashMap::new(),
    };
    // Comment lines, the header, then `path<TAB>status<TAB>description`
    // sorted by path, so siblings arrive in name order.
    for line in HIERARCHY_TABLE
        .lines()
        .filter(|l| !l.starts_with('#'))
        .skip(1)
    {
        let mut fields = line.splitn(3, '\t');
        let (Some(path), Some(_status), Some(description)) =
            (fields.next(), fields.next(), fields.next())
        else {
            panic!("malformed WIS2 topic hierarchy row: {line:?}");
        };
        let (parent, name) = path.rsplit_once('/').unwrap_or(("", path));
        hierarchy.descriptions.insert(path, description);
        hierarchy.children.entry(parent).or_default().push(name);
    }
    hierarchy
});

/// Why a WIS2 topic is not one.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum TopicError {
    #[error("WIS2 topic must not be empty")]
    Empty,
    #[error("WIS2 topic '{topic}': level '{level}' must be lowercase letters, digits and hyphens")]
    Malformed { topic: String, level: String },
    /// `level` is not one of the names `parent` may have below it.
    #[error(
        "WIS2 topic '{topic}': unknown level '{level}' {}; expected one of: {}",
        position(.parent),
        .expected.join(", ")
    )]
    UnknownLevel {
        topic: String,
        level: String,
        parent: String,
        expected: Vec<&'static str>,
    },
    #[error("WIS2 topic '{topic}': '{parent}' has no levels below it")]
    BelowLeaf { topic: String, parent: String },
}

fn position(parent: &str) -> String {
    if parent.is_empty() {
        "as the earth-system discipline".into()
    } else {
        format!("below '{parent}'")
    }
}

/// A WIS2 topic from its earth-system-discipline level down, valid in the
/// vendored hierarchy: every level is one its parent lists, except those
/// below an `experimental` level, which WIS2 leaves to the publisher.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Deserialize)]
#[serde(try_from = "String")]
pub struct Wis2Topic(String);

impl Wis2Topic {
    /// Validate `topic`, naming the first level the hierarchy does not have
    /// and the levels it allows there.
    pub fn parse(topic: &str) -> Result<Self, TopicError> {
        let topic = topic.trim();
        if topic.is_empty() {
            return Err(TopicError::Empty);
        }
        let hierarchy = &*HIERARCHY;
        let mut end = 0usize;
        let mut free = false;
        for level in topic.split('/') {
            let well_formed = !level.is_empty()
                && level
                    .bytes()
                    .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-');
            if !well_formed {
                return Err(TopicError::Malformed {
                    topic: topic.into(),
                    level: level.into(),
                });
            }
            let parent = &topic[..end.saturating_sub(1)];
            end += level.len() + 1;
            if free {
                continue;
            }
            let path = &topic[..end - 1];
            if hierarchy.descriptions.contains_key(path) {
                free = level == EXPERIMENTAL;
                continue;
            }
            return Err(match hierarchy.children.get(parent) {
                Some(expected) => TopicError::UnknownLevel {
                    topic: topic.into(),
                    level: level.into(),
                    parent: parent.into(),
                    expected: expected.clone(),
                },
                None => TopicError::BelowLeaf {
                    topic: topic.into(),
                    parent: parent.into(),
                },
            });
        }
        Ok(Self(topic.into()))
    }

    /// The topic a WIS2 subscription filter names: the filter without its
    /// `{channel}/a/wis2/{centre-id}/data/{data-policy}/` levels, cut at its
    /// first wildcard, down to the deepest level the hierarchy has. A `+`
    /// may stand for any of those leading levels; `None` when the filter is
    /// not a data subscription or names no discipline.
    pub fn from_subscription(filter: &str) -> Option<Self> {
        const LEADING: [&[&str]; 6] = [
            &["cache", "origin"],
            &["a"],
            &["wis2"],
            &[], // centre-id: any
            &["data"],
            &["core", "recommended"],
        ];
        let mut levels = filter.trim().split('/');
        for allowed in LEADING {
            let level = levels.next()?;
            let known = allowed.is_empty() || allowed.contains(&level);
            if level != "+" && (level.is_empty() || level == "#" || !known) {
                return None;
            }
        }
        let rest: Vec<&str> = levels.take_while(|l| !matches!(*l, "+" | "#")).collect();
        (1..=rest.len())
            .rev()
            .find_map(|depth| Self::parse(&rest[..depth].join("/")).ok())
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }

    /// The hierarchy's description of the topic's last level; `None` for a
    /// level a publisher added below `experimental`.
    pub fn title(&self) -> Option<&'static str> {
        HIERARCHY.descriptions.get(self.0.as_str()).copied()
    }

    /// The topic's concept URL in [`TOPIC_SCHEME`].
    pub fn url(&self) -> String {
        format!("{TOPIC_SCHEME}/{}", self.0)
    }
}

impl TryFrom<String> for Wis2Topic {
    type Error = TopicError;

    fn try_from(topic: String) -> Result<Self, Self::Error> {
        Self::parse(&topic)
    }
}

impl std::fmt::Display for Wis2Topic {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.0)
    }
}

/// A collection's WIS2 topics: its configured `[discovery] wis2_topic`, or
/// else the distinct topics its WIS2 subscriptions (`[cap.wis2]`,
/// `[bufr.wis2]`) name, in subscription order. An engine gaining a WIS2
/// source adds its subscriptions here.
pub fn topics(config: &CollectionConfig) -> Vec<Wis2Topic> {
    if let Some(topic) = config
        .discovery
        .as_ref()
        .and_then(|d| d.wis2_topic.as_ref())
    {
        return vec![topic.clone()];
    }
    let subscriptions = [
        config.cap.as_ref().and_then(|c| c.wis2.as_ref()),
        config.bufr.as_ref().and_then(|b| b.wis2.as_ref()),
    ];
    let mut topics: Vec<Wis2Topic> = Vec::new();
    for filter in subscriptions.into_iter().flatten().flat_map(|w| &w.topics) {
        if let Some(topic) = Wis2Topic::from_subscription(filter) {
            if !topics.contains(&topic) {
                topics.push(topic);
            }
        }
    }
    topics
}

/// An OGC API - Records `theme`: concepts from one scheme.
#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct Theme {
    pub scheme: &'static str,
    pub concepts: Vec<Concept>,
}

/// One concept of a [`Theme`].
#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct Concept {
    pub id: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub title: Option<&'static str>,
    pub url: String,
}

/// The `themes` of a collection with `topics`: one theme of
/// [`TOPIC_SCHEME`] holding a concept per topic, whose id is the topic path
/// and whose title is its last level's description. Empty without topics.
///
/// The one place the encoding is decided. The MetOcean Common profile has
/// not settled it: WCMP2 records give each level a theme of its own instead.
pub fn themes(topics: &[Wis2Topic]) -> Vec<Theme> {
    if topics.is_empty() {
        return Vec::new();
    }
    let concepts = topics
        .iter()
        .map(|topic| Concept {
            id: topic.0.clone(),
            title: topic.title(),
            url: topic.url(),
        })
        .collect();
    vec![Theme {
        scheme: TOPIC_SCHEME,
        concepts,
    }]
}

/// The longest record id accepted.
pub const MAX_RECORD_ID_LEN: usize = 255;

const RECORD_ID_PREFIX: &str = "urn:wmo:md:";

/// Why a WCMP2 record id is not one.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
#[error(
    "WCMP2 record id '{0}' must be urn:wmo:md:<centre-id>:<local-id>, at most \
     {MAX_RECORD_ID_LEN} letters, digits and the characters - _ . :"
)]
pub struct RecordIdError(String);

/// A WCMP2 discovery record identifier, `urn:wmo:md:<centre-id>:<local-id>`.
/// Its characters are ASCII letters, digits and `-_.:`, all of which a URL
/// path segment and HTML carry as they are.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Deserialize)]
#[serde(try_from = "String")]
pub struct RecordId(String);

impl RecordId {
    pub fn parse(id: &str) -> Result<Self, RecordIdError> {
        let id = id.trim();
        let well_formed = id.len() <= MAX_RECORD_ID_LEN
            && id.strip_prefix(RECORD_ID_PREFIX).is_some_and(|rest| {
                rest.split_once(':')
                    .is_some_and(|(centre, local)| !centre.is_empty() && !local.is_empty())
            })
            && id
                .chars()
                .all(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '.' | ':'));
        if well_formed {
            Ok(Self(id.into()))
        } else {
            Err(RecordIdError(id.into()))
        }
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl TryFrom<String> for RecordId {
    type Error = RecordIdError;

    fn try_from(id: String) -> Result<Self, Self::Error> {
        Self::parse(&id)
    }
}

impl std::fmt::Display for RecordId {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.0)
    }
}

/// Why a catalogue base URL is not one.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
#[error("[discovery] catalogue '{0}' must be an http(s) URL with a host and no query or fragment")]
pub struct CatalogueError(String);

/// The base URL of a WIS2 Global Discovery Catalogue (an OGC API - Records
/// service), without a trailing slash.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
#[serde(try_from = "String")]
pub struct Catalogue(String);

impl Catalogue {
    pub fn parse(url: &str) -> Result<Self, CatalogueError> {
        let url = url.trim().trim_end_matches('/');
        let host = url
            .strip_prefix("https://")
            .or_else(|| url.strip_prefix("http://"));
        let well_formed = host.is_some_and(|h| !h.is_empty() && !h.starts_with('/'))
            && url
                .chars()
                .all(|c| c.is_ascii_graphic() && !matches!(c, '?' | '#'));
        if well_formed {
            Ok(Self(url.into()))
        } else {
            Err(CatalogueError(url.into()))
        }
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }

    /// The record's GeoJSON in the catalogue's `wis2-discovery-metadata`
    /// collection.
    pub fn record_url(&self, record: &RecordId) -> String {
        format!(
            "{}/collections/wis2-discovery-metadata/items/{}",
            self.0,
            path_segment(record.as_str())
        )
    }
}

impl Default for Catalogue {
    fn default() -> Self {
        Self(DEFAULT_CATALOGUE.into())
    }
}

impl TryFrom<String> for Catalogue {
    type Error = CatalogueError;

    fn try_from(url: String) -> Result<Self, Self::Error> {
        Self::parse(&url)
    }
}

/// `value` as one URL path segment: everything but an RFC 3986 `pchar`
/// percent-encoded. A record id's `:` stays as it is.
fn path_segment(value: &str) -> String {
    let mut out = String::with_capacity(value.len());
    for b in value.bytes() {
        if b.is_ascii_alphanumeric() || b"-._~!$&'()*+,;=:@".contains(&b) {
            out.push(b as char);
        } else {
            out.push_str(&format!("%{b:02X}"));
        }
    }
    out
}

/// What a collection description reads beyond the collection's own
/// config: the catalogue its records resolve in. The server builds one per
/// accepted load from `[discovery] catalogue` and gives it to every API, so
/// a reload changing only the catalogue rebuilds no engine.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct Discovery {
    catalogue: Catalogue,
}

impl Discovery {
    pub fn new(catalogue: Catalogue) -> Self {
        Self { catalogue }
    }

    pub fn catalogue(&self) -> &Catalogue {
        &self.catalogue
    }

    /// The WCMP2 records describing `config`: its `[discovery]
    /// wcmp2_record`. Records a collection's WIS2 notifications name are
    /// to join these, looked up by the collection's id.
    pub fn records<'a>(
        &'a self,
        config: &'a CollectionConfig,
    ) -> impl Iterator<Item = &'a RecordId> {
        config
            .discovery
            .as_ref()
            .and_then(|d| d.wcmp2_record.as_ref())
            .into_iter()
    }
}

